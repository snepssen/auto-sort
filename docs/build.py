def block(item):
    kind = item["kind"]
    if kind == "prose":
        css = f' class="{item["class"]}"' if item.get("class") else ""
        return "\n".join(f"  <p{css}>{text}</p>" for text in item["text"])
    if kind == "heading":
        return f'  <h3>{item["text"]}</h3>'
    if kind == "figure":
        return figure(item)
    if kind == "report":
        caption = (f'\n<p class="caption">{item["caption"]}</p>'
                   if item.get("caption") else "")
        return (f'  <div class="figure">\n<pre class="report mono">'
                f'{item["text"]}</pre>{caption}\n</div>')
    if kind == "cards":
        cards = "\n".join(
            f'    <div class="card"><h3>{card["title"]}</h3>'
            f'<p class="mono">{card["formats"]}</p><p>{card["note"]}</p></div>'
            for card in item["cards"]
        )
        return f'  <div class="cards">\n{cards}\n  </div>'
    if kind == "raw":
        return item["html"]
    raise SystemExit(f"build.py does not know the block kind {kind!r}")


def figure(item):
    """A screenshot, with the dark variant swapped in by the browser."""
    dark = (f'\n      <source srcset="{item["dark"]}" '
            f'media="(prefers-color-scheme: dark)">' if item.get("dark") else "")
    return f"""  <figure class="shot">
    <picture>{dark}
      <img src="{item['light']}" alt="{item['alt']}" width="{item['width']}"
           height="{item['height']}" loading="{item.get('loading', 'lazy')}"
           decoding="async">
    </picture>
    <figcaption>{item['caption']}</figcaption>
  </figure>"""


def badge(page, ecosystem):
    """The line above the name: where it runs, from the support table, and the
    licence. A page whose project has no table keeps the badge it wrote."""
    meta = page["meta"]
    project = next(p for p in ecosystem["projects"] if p["slug"] == meta["slug"])
    if "support" in project and meta.get("license"):
        return f"{platforms(project)} · {meta['license']}"
    return meta["badge"]


def header(page, ecosystem):
    meta = page["meta"]
    stats = "\n".join(f"    <span>{stat}</span>" for stat in meta["stats"])
    blocks = "\n".join(block(item) for item in page.get("header_blocks", []))
    blocks = blocks + "\n" if blocks else ""
    extra = partial(meta["header_extra"]) + "\n" if meta.get("header_extra") else ""
    return f"""
<div class="wrap">
<header id="top" class="mast">
  <span class="badge"><span class="dot"></span>{badge(page, ecosystem)}</span>
  <h1>{meta['name']}</h1>
{extra}  <p class="subhead">{meta['subhead']}</p>
  <div class="headmeta">
{stats}
  </div>
</header>
</div>
<div class="wrap">
{blocks}"""


def partial(name):
    """Bespoke markup, kept as markup in a file an editor understands."""
    path = HERE / "sections" / name
    if not path.is_file():
        raise SystemExit(f"build.py cannot find sections/{name}")
    return path.read_text(encoding="utf-8").rstrip("\n")


def section_blocks(item):
    if item.get("body"):
        return partial(item["body"])
    return "\n".join(block(b) for b in item["blocks"])


# A page leads with what the thing is and how to get it; the long explanations
# are kept, word for word, but folded. A section marked `fold` shows its
# heading and its one-line `teaser`, and opens to everything else. Folded
# sections are gathered into one group, with one entry in the jump navigation,
# so a long page does not need a long nav. The group stands where a
# `{"folds": True}` marker does, or else where the first folded section does,
# so a page can keep its sections in reading order and still put the group
# after the part that says how to get it.
FOLDS = {"id": "in-depth", "jump": "How it works", "eyebrow": "In depth",
         "heading": "How it works"}


def folds_copy(page):
    return {**FOLDS, **page["meta"].get("folds", {})}


def fold_anchor(page):
    """The item the group is drawn in place of: the marker, or the first fold."""
    items = page["sections"]
    return next((item for item in items if item.get("folds")),
                next((item for item in items if item.get("fold")), None))


def folded(item):
    teaser = (f'<span class="fold__teaser">{item["teaser"]}</span>'
              if item.get("teaser") else "")
    return f"""  <details class="fold" id="{item['id']}">
    <summary><span class="fold__title">{item['heading']}</span>{teaser}</summary>
    <div class="fold__body">
{section_blocks(item)}
    </div>
  </details>"""


def fold_group(page, items):
    copy = folds_copy(page)
    if any(item.get("id") == copy["id"] for item in page["sections"]):
        raise SystemExit(f"a section already has the id {copy['id']!r}; "
                         f"give the group another in meta['folds']['id']")
    inner = "\n".join(folded(item) for item in items)
    return f"""
<section id="{copy['id']}" class="folds">
  <p class="eyebrow">{copy['eyebrow']}</p>
  <h2>{copy['heading']}</h2>
{inner}
</section>
"""


def section(item):
    blocks = section_blocks(item)
    identifier = f' id="{item["id"]}"' if item.get("id") else ""
    identifier += f' {item["attrs"]}' if item.get("attrs") else ""
    eyebrow = (f'  <p class="eyebrow">{item["eyebrow"]}</p>\n'
               if item.get("eyebrow") else "")
    title = f"  <h2>{item['heading']}</h2>\n" if item.get("heading") else ""
    return f"""
<section{identifier}>
{eyebrow}{title}{blocks}
</section>
"""


def footer(page):
    """Plain `<footer>`, as the siblings have it.

    Not `<footer class="contact">`: `.contact` is the flex row of link buttons
    used inside a contact section, and siphon had picked it up by accident,
    laying its two closing lines out side by side.
    """
    scripts = "".join(f'<script src="{src}"></script>\n'
                      for src in page["meta"].get("scripts", []))
    lines = page["footer"]
    if len(lines) == 1:
        body = f"  {lines[0]}"
    else:
        body = "\n".join(f"  <p>{line}</p>" for line in lines)
    return f"""
<footer>
{body}
</footer>

</div>

{scripts}<script src="ecosystem.js"></script>
</body>
</html>
"""


def project_relationships(ecosystem, slug):
    project = next(p for p in ecosystem["projects"] if p["slug"] == slug)
    return project.get("relationships") or []


def relationships(ecosystem, slug):
    """How this piece is made from the others, from the shared catalogue.

    The sentence is authored beside the project, with `{name}` where the other
    project's name should be linked. It is the same arrangement as page prose:
    written by whoever owns the catalogue, and not escaped. A project with no
    relationships contributes nothing, so every other page stays as it was.
    """
    rels = project_relationships(ecosystem, slug)
    if not rels:
        return ""
    known = {p["slug"]: p for p in ecosystem["projects"]}
    paragraphs = []
    for rel in rels:
        other = known.get(rel.get("slug"))
        text = rel.get("text") or ""
        if other is None or other["slug"] == slug or "{name}" not in text:
            raise SystemExit(
                f"ecosystem.json: {slug} has a relationship that does not "
                f"name another project and a sentence with {{name}} in it "
                f"({rel.get('slug')!r})")
        link = f'<a href="{other["url"]}">{other["name"]}</a>'
        paragraphs.append(f"  <p>{text.replace('{name}', link)}</p>")
    body = "\n".join(paragraphs)
    return f"""
<section id="with">
  <p class="eyebrow">The workshop</p>
  <h2>Made from the pieces beside it</h2>
{body}
</section>
"""


def render():
    page = load_page()
    ecosystem = load_ecosystem()
    slug = page["meta"]["slug"]
    parts = [head(page, ecosystem), rail(ecosystem, slug, page), header(page, ecosystem)]
    placed = False
    beside = relationships(ecosystem, slug)
    folds = [item for item in page["sections"] if item.get("fold")]
    anchor = fold_anchor(page)
    for item in page["sections"]:
        if item is anchor and folds:  # the folded sections, gathered here
            parts.append(fold_group(page, folds))
        if item.get("fold") or item.get("folds"):
            continue
        if item.get("grid"):          # the ecosystem grid, in its place
            if beside:
                parts.append(beside)
                beside = ""
            parts.append(grid(ecosystem, slug))
            placed = True
        else:
            parts.append(section(item))
    if beside:
        parts.append(beside)
    if not placed:                    # no marker: it closes the page
        parts.append(grid(ecosystem, slug))
    parts.append(contact(page, ecosystem))
    parts.append(footer(page))
    return "".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if index.html does not match the catalogue")
    args = parser.parse_args()

    built = render()
    target = HERE / "index.html"

    if args.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        if current != built:
            print("docs/index.html is out of date — run python3 docs/build.py",
                  file=sys.stderr)
            return 1
        print("docs/index.html matches the catalogue.")
        return 0

    target.write_text(built, encoding="utf-8")
    page = load_page()
    print(f"docs/index.html — {len(built.splitlines())} lines, "
          f"{len([s for s in page['sections'] if not s.get('grid')])} sections, "
          f"{len(load_ecosystem()['projects'])} projects in the rail")
    return 0


if __name__ == "__main__":
    sys.exit(main())
